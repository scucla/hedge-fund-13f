"""Task C results table: baselines vs models on the held-out test years.

Usage (after task_c_baselines, task_c1, task_c2 run):
    uv run python -m src.models.task_c_report    # -> docs/task_c_results.md
"""

import json

import polars as pl

from src.models.task_c1 import OUT as C1_OUT
from src.models.task_c2 import RESULTS_PATH as C2_RESULTS
from src.models.task_c_baselines import c1_table
from src.models.task_c_common import frames, load_c1, md_table
from src.securities import db

DOC = "docs/task_c_results.md"
C1_COLS = ["model", "n", "macro_f1", "log_loss", "exit_auc", "P_exit", "R_exit", "P_add", "R_add", "R_trim", "R_hold"]
C2_COLS = ["method", "fund_quarters", "recall@20", "ndcg@20", "hit_rate", "reachable"]


def c1_section(res: pl.DataFrame, base: pl.DataFrame, split: str, subset: str) -> str:
    b = base.filter((pl.col("split") == split) & (pl.col("subset") == subset)).rename({"baseline": "model"})
    m = res.filter((pl.col("split") == split) & (pl.col("subset") == subset)).rename({"variant": "model"})
    return md_table(pl.concat([b.select(C1_COLS), m.select(C1_COLS)]))


def main() -> None:
    with db.connect(read_only=True) as con:
        df = load_c1(con)
    base = c1_table(frames(df))
    res = pl.read_parquet(f"{C1_OUT}_results.parquet")
    lift = pl.read_parquet(f"{C1_OUT}_lift.parquet")
    shap = pl.read_parquet(f"{C1_OUT}_shap.parquet")
    choices = json.load(open(f"{C1_OUT}_choices.json"))
    c2 = pl.read_parquet(C2_RESULTS)
    final = choices["final"]

    style = (res.filter((pl.col("variant") == final) & (pl.col("split") == "test") & pl.col("subset").str.starts_with("style:"))
             .with_columns(pl.col("subset").str.replace("style:", "").alias("style"))
             .select("style", "n", "macro_f1", "log_loss", "exit_auc", "R_exit", "R_add"))

    def c2_tab(split, cohort, subset):
        t = c2.filter((pl.col("split") == split) & (pl.col("cohort") == cohort) & (pl.col("subset") == subset))
        order = {m: i for i, m in enumerate(["popularity", "cluster_popularity", "reentry", "item_cf", "als"])}
        return md_table(t.with_columns(pl.col("method").replace_strict(order).alias("o")).sort("o").select(C2_COLS))

    c2_choice = (c2.filter(pl.col("split") == "test").select("method", "params").unique().sort("method"))
    c2_grid = (c2.filter((pl.col("split") == "val_grid") & (pl.col("subset") == "all"))
               .select("method", "params", "ndcg@20", "recall@20").sort("method", "ndcg@20", descending=[False, True]))
    val_tab = pl.DataFrame([{"variant": n, "params": json.dumps(c["params"]), "val_log_loss": c["val_log_loss"]}
                            for n, c in choices.items() if n != "final"])

    text = f"""# Task C results: next-quarter moves (C1) and new buys (C2)

Generated by `src/models/task_c_report.py`. Splits: train 2018-2021, validate 2022, **test 2023Q1-2026Q1**.
Baselines were written to `docs/task_c_baselines.md` and committed before any model was trained. Every
choice below was made on 2022; test numbers were computed once. Leakage checks: `docs/task_c_leakage_audit.md`.

Each table is shown on **all rows** and **without rows whose return label is a 0% deal fallback or missing**
(`ret_clean`). C1 labels never depend on a return, so the second view is a robustness check on a subset.

## C1: exit / trim / hold / add

Validation choices (lowest 2022 log-loss wins; final model: **{final}**):

{md_table(val_tab, 4)}

### Test, seed funds, all rows

{c1_section(res, base, "test", "all")}

### Test, seed funds, without 0%-fallback / missing returns

{c1_section(res, base, "test", "ret_clean")}

### Test, seed funds, without multi-manager and quant funds

{c1_section(res, base, "test", "excl_multi_quant")}

### Test, holdout funds (never trained on, no clusters)

{c1_section(res, base, "test_holdout", "all")}

### Test, holdout funds, without 0%-fallback / missing returns

{c1_section(res, base, "test_holdout", "ret_clean")}

### Lift from peer and cluster features (test, paired bootstrap over fund-quarters, 95% interval)

Negative log-loss difference = better.

{md_table(lift, 4)}

### Final model by style (test, seed)

{md_table(style)}

### SHAP (final model, 5,000 test positions; mean |SHAP| in log-odds, top 20)

Figures: `docs/figures/19_c1_shap_exit.png`, `docs/figures/20_c1_shap_add.png`; calibration
`docs/figures/18_c1_calibration.png`.

{md_table(shap.head(20), 4)}

## C2: new buys, top 20

Chosen settings (2022 NDCG@20): {", ".join(f"{m} {p}" for m, p in c2_choice.iter_rows() if p != "{}")}

### Test, seed funds, all new buys

{c2_tab("test", "seed", "all")}

### Test, seed funds, without 0%-fallback / missing returns

{c2_tab("test", "seed", "ret_clean")}

### Test, seed funds, without multi-manager and quant funds

{c2_tab("test", "seed", "excl_multi_quant")}

### Test, holdout funds

{c2_tab("test", "holdout", "all")}

### Test, holdout funds, without 0%-fallback / missing returns

{c2_tab("test", "holdout", "ret_clean")}

### Validation grid (2022, seed)

{md_table(c2_grid, 4)}
"""
    with open(DOC, "w") as f:
        f.write(text)
    print(text)


if __name__ == "__main__":
    main()
